package de.university.staffmanagement.enums;

/**
 * Enum representing the approval status of a leave request.
 *
 * <ul>
 *     <li>{@code PENDING} – Awaiting review or decision</li>
 *     <li>{@code APPROVED} – Request has been approved</li>
 *     <li>{@code REJECTED} – Request has been denied</li>
 * </ul>
 */
public enum Status {
    PENDING,
    APPROVED,
    REJECTED
}
